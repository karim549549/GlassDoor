/**
 * Generates .agents/reference/PROJECT_MAP.md from the repository itself.
 *
 * WHY THIS IS GENERATED AND NOT HAND-WRITTEN
 *
 * Every subagent starts with a cold context: it inherits none of the calling
 * session's knowledge, only AGENTS.md plus its prompt. It then rediscovers the
 * codebase by reading and grepping. In one session of this project that cost
 * roughly 300k tokens across three exploration agents alone, for a map that was
 * discarded the moment they exited.
 *
 * A hand-maintained map would fix that until it drifted - and a stale map is
 * worse than none, because an agent trusts it and acts on it. This repo has
 * already shipped comments asserting the opposite of what the code did. So the
 * map is derived from the source of truth (the Prisma schema, the route files,
 * the directory tree) and regenerated rather than edited.
 *
 * Run: npm run map
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join, relative, sep } from "node:path";

const root = process.cwd();
const posix = (p) => p.split(sep).join("/");

function walk(dir, filter) {
  const out = [];
  let entries;
  try { entries = readdirSync(dir, { withFileTypes: true }); } catch { return out; }
  for (const e of entries) {
    if (e.name === "node_modules" || e.name === ".next" || e.name === ".git") continue;
    const full = join(dir, e.name);
    if (e.isDirectory()) out.push(...walk(full, filter));
    else if (filter(e.name)) out.push(full);
  }
  return out;
}

/* ---------------------------------------------------------------- schema -- */
const schemaFiles = walk(join(root, "prisma/schema"), (n) => n.endsWith(".prisma"));
const models = [];
const enums = [];
for (const f of schemaFiles) {
  const src = readFileSync(f, "utf8");
  const rel = posix(relative(root, f));
  for (const m of src.matchAll(/^model\s+(\w+)\s*\{/gm)) models.push({ name: m[1], file: rel });
  for (const m of src.matchAll(/^enum\s+(\w+)\s*\{/gm)) {
    const body = src.slice(m.index).match(/\{([^}]*)\}/);
    const values = body ? body[1].split("\n").map((l) => l.trim()).filter((l) => l && !l.startsWith("//")) : [];
    enums.push({ name: m[1], file: rel, values });
  }
}

const migrations = readdirSync(join(root, "prisma/schema/migrations"), { withFileTypes: true })
  .filter((d) => d.isDirectory()).map((d) => d.name).sort();

/* ----------------------------------------------------------------- routes -- */
const routeFiles = walk(join(root, "app/api"), (n) => n === "route.ts");
const routes = routeFiles.map((f) => {
  const src = readFileSync(f, "utf8");
  const methods = [...src.matchAll(/export async function (GET|POST|PATCH|PUT|DELETE)/g)].map((m) => m[1]);
  const url = "/" + posix(relative(join(root, "app"), f)).replace(/\/route\.ts$/, "");
  const gate = src.includes("requireRole(") ? "requireRole"
    : src.includes("requireUser(") ? "requireUser"
    : src.includes("getOptionalUser(") ? "optional"
    : "public";
  const limited = /checkRateLimit\(/.test(src);
  return { url, methods, gate, limited };
}).sort((a, b) => a.url.localeCompare(b.url));

/* ------------------------------------------------------------------ pages -- */
const pages = walk(join(root, "app"), (n) => n === "page.tsx")
  .map((f) => "/" + posix(relative(join(root, "app"), f)).replace(/\/?page\.tsx$/, ""))
  .map((p) => (p === "/" ? "/" : p))
  .sort();

/* ------------------------------------------------------------------- libs -- */
const libDirs = readdirSync(join(root, "lib"), { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => {
    const files = readdirSync(join(root, "lib", d.name)).filter((f) => f.endsWith(".ts") && !f.endsWith(".test.ts"));
    return { name: d.name, files };
  });

/* ------------------------------------------------------------------ tests -- */
const tests = walk(join(root, "lib"), (n) => n.endsWith(".test.ts"))
  .map((f) => posix(relative(root, f))).sort();

/* ------------------------------------------------------------------ write -- */
const outDir = join(root, ".agents/reference");
if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true });

const md = `<!-- GENERATED by scripts/generate-project-map.mjs — do not edit by hand.
     Regenerate with \`npm run map\`. Hand edits are lost and, worse, drift. -->

# Project map

Auto-derived inventory of Devs Arena. Read this before exploring the codebase —
it exists so an agent does not spend tokens rediscovering structure.

Generated from ${models.length} models, ${routes.length} API routes, ${pages.length} pages, ${tests.length} test files.

## Data model (${models.length} models, ${migrations.length} migrations)

${[...new Set(models.map((m) => m.file))].sort().map((file) => {
  const inFile = models.filter((m) => m.file === file).map((m) => m.name);
  return `- \`${file}\` — ${inFile.join(", ")}`;
}).join("\n")}

### Enums
${enums.sort((a, b) => a.name.localeCompare(b.name)).map((e) =>
  `- \`${e.name}\` — ${e.values.join(" · ")}`).join("\n")}

### Migrations (chronological; never edit an applied one)
${migrations.map((m) => `- \`${m}\``).join("\n")}

## API routes (${routes.length})

| Route | Methods | Auth | Rate limited |
|---|---|---|---|
${routes.map((r) => `| \`${r.url}\` | ${r.methods.join(", ") || "—"} | ${r.gate} | ${r.limited ? "yes" : "no"} |`).join("\n")}

## Pages (${pages.length})

${pages.map((p) => `- \`${p}\``).join("\n")}

## Domain libraries

${libDirs.map((d) => `- \`lib/${d.name}/\` — ${d.files.join(", ")}`).join("\n")}

## Tests (${tests.length} files)

${tests.map((t) => `- \`${t}\``).join("\n")}

Run with \`npm test\` (uses \`scripts/run-tests.mjs\`; Node 20 here cannot glob in
\`node --test\`, so the runner walks \`lib/\` itself).
`;

writeFileSync(join(outDir, "PROJECT_MAP.md"), md);
console.log(
  `Wrote .agents/reference/PROJECT_MAP.md — ` +
  `${models.length} models, ${enums.length} enums, ${routes.length} routes, ` +
  `${pages.length} pages, ${libDirs.length} lib domains, ${tests.length} test files`
);
